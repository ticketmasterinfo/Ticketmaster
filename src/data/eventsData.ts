export function calculateDateInfo(daysOffset: number, hour: number = 19, minute: number = 30): DateInfo {
  const now = new Date();
  const targetDate = new Date(now.getTime());
  targetDate.setDate(now.getDate() + daysOffset);
  targetDate.setHours(hour, minute, 0, 0);

  const months = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'];
  const dows = ['SUN', 'MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT'];

  const month = months[targetDate.getMonth()];
  const day = targetDate.getDate();
  const dow = dows[targetDate.getDay()];
  const year = targetDate.getFullYear();

  const timeString = `${(hour % 12) || 12}:${minute.toString().padStart(2, '0')} ${hour >= 12 ? 'PM' : 'AM'}`;
  const fullDate = `${dow}, ${month} ${day}, ${year} • ${timeString}`;

  return {
    month,
    day,
    dow,
    fullDate,
    time: timeString,
    timestamp: targetDate.getTime(),
  };
}

